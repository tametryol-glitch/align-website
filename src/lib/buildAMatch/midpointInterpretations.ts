export interface MidpointReading {
  /** Plain-language name. Shown alongside the technical pair, never instead. */
  name: string;
  /** What it brings when their body lands here. */
  light: string;
  /** What the same contact costs. Never omitted. */
  shadow: string;
}

/** Order-independent key: Sun/Moon and Moon/Sun are one entry. */
export function midpointKey(a: string, b: string): string {
  return [a, b].sort().join('/');
}

