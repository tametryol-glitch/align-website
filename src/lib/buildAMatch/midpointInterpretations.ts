/** The reading for a midpoint pair, if one is written. */
export function readingForMidpoint(a: string, b: string): MidpointReading | null {
  return MIDPOINT_READINGS[midpointKey(a, b)] ?? null;
}

/** Is this one of the 13 already flagged as toxicity potential? */
export function isShadowMidpoint(a: string, b: string): boolean {
  return SHADOW_MIDPOINTS.has(midpointKey(a, b));
}

/** How the activation is phrased: their body landing on your point. */
export function describeActivation(
  activatingBody: string, a: string, b: string,
): string {
  return `Their ${activatingBody} sits on your ${a}/${b}`;
}
